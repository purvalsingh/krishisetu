const DICTIONARIES: Record<Locale, Dictionary> = { en, mr, hi };

export const isLocale = (value: string): value is Locale => value in DICTIONARIES;

/** Returns a lookup that falls back to English, and then to the key itself. */
export function translator(locale: string) {
  const dict = isLocale(locale) ? DICTIONARIES[locale] : en;
  return (key: keyof typeof en) => dict[key] ?? en[key] ?? String(key);
}
